// Optional synthetic browser acceptance. No backend: every API request is intercepted.
// Run after npm run build, with PLAYWRIGHT_MODULE pointing to a Playwright module if not installed locally.
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { preview } from 'vite';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const output = resolve(process.env.UI_EVIDENCE_DIR || '../../m4-ui1-evidence');
await mkdir(output, {recursive:true});
const server = await preview({preview:{host:'127.0.0.1',port:4179,strictPort:true}});
const browser = await chromium.launch({headless:true, ...(process.env.UI_BROWSER_PATH ? {executablePath:process.env.UI_BROWSER_PATH} : {})});
const context = await browser.newContext({viewport:{width:1440,height:1080},serviceWorkers:'block'});
const base = 'http://127.0.0.1:4179';
const root = '/admin/knowledge-protocols';
let write = true, listFails = false, checks = 0;
const writes = [], errors = [];
const participant = {enrollment_id:'synthetic-person',obligation_id:'synthetic-obligation',learner_name:'Тестовый участник',knowledge_check_date:null,knowledge_check_result:null};
const draft = {id:'draft',status:'draft',course_id:'synthetic-course',protocol_number:'UI-001',protocol_date:'2026-11-05',updated_at:'2026-11-05T00:00:00Z',participant_count:1,participants:[participant],commission_members:[],is_signed:false,signed_scan_available:false};
const recorded = {...draft,id:'recorded',protocol_number:'UI-002',status:'recorded'};
const signed = {...recorded,id:'signed',protocol_number:'UI-003',is_signed:true,signed_on:'2026-11-05',signed_scan_available:true,signed_scan_size:100};
const older = {...draft,id:'older',protocol_number:'UI-OLDER'};
await context.addInitScript(() => sessionStorage.setItem('obrportal_access_token','synthetic-ui-test'));
await context.route('**/*', async route => {
  const req = route.request(), url = new URL(req.url());
  if (url.origin !== base) return route.abort();
  if (!url.pathname.startsWith('/api/') && url.pathname !== '/health') return route.continue();
  const json = (body,status=200) => route.fulfill({status,contentType:'application/json',body:JSON.stringify(body)});
  const path = url.pathname;
  if (req.method() !== 'GET') {
    writes.push({path,method:req.method(),body:req.postDataJSON()});
    if (path.endsWith('/protocol-drafts') && req.method() === 'POST') return json({...draft,id:'created',protocol_number:req.postDataJSON().protocol_number});
    return json({detail:'Unexpected synthetic mutation'},409);
  }
  if (path === '/api/v1/auth/me') return json({id:'synthetic-admin',email:'ui-test@example.invalid',roles:[{code:'admin'}]});
  if (path.endsWith('/me/permissions')) return json({mintrud:{read:true,write}});
  if (path.endsWith('/courses')) return json([{id:'synthetic-course',title:'Тестовая программа охраны труда'}]);
  if (path.endsWith('/protocol-candidates')) return json([{enrollment_id:'new-person',learner_name:'Новый тестовый участник',completed_at:'2026-11-04'}, ...Array.from({length:67}, (_,i) => ({enrollment_id:`candidate-${i}`,learner_name:`Кандидат ${i}`,completed_at:'2026-11-04'}))]);
  if (path.endsWith('/protocol-drafts')) return listFails ? json({detail:'Synthetic unavailable'},503) : json([draft,recorded,signed]);
  if (path.endsWith('/print-preview')) return json({...draft,document_kind:'DRAFT_PREVIEW_ONLY'});
  if (path.endsWith('/recording-readiness')) return json({fieldsComplete:false,issues:[{code:'order_number',message:'Укажите номер приказа о создании комиссии.'},{code:'central_employer:synthetic-person',message:'Заполните центральные реквизиты DOCUMENT_ORG_NAME и DOCUMENT_ORG_INN.'},{code:'workplace:synthetic-person',message:'Укажите название и ИНН работодателя слушателя.'}],advisories:[]});
  if (path.endsWith('/registry-reconciliation')) {
    const id = path.split('/').at(-2);
    return json({protocol_id:id,protocol_status:'draft',members:[{...participant,fields:{protocol_number:{source:'UI-001',existing:null}},history_reasons:[],structural_issues:[],verdict:'missing_target_fields'}]});
  }
  if (path.includes('/protocol-drafts/')) {
    const p = [draft,recorded,signed,older,{...draft,id:'created',protocol_number:'UI-NEW'}].find(p => path.endsWith('/'+p.id));
    return p ? json(p) : json({detail:'Not found'},404);
  }
  if (path === '/health' || path.endsWith('/ready')) return json({status:'ok'});
  return json([]);
});
const page = await context.newPage();
page.on('pageerror', error => errors.push(error.message));
const check = (condition,message) => {assert.ok(condition,message); checks++;};
const goto = path => page.goto(base+path);
try {
  await goto(root);
  await page.getByRole('heading',{name:'Протоколы проверки знаний',exact:true}).waitFor();
  await page.getByRole('link',{name:'Открыть протокол № UI-001'}).waitFor();
  check(await page.locator('aside a[href="'+root+'"]').count() > 0,'administrative menu entry');
  check(await page.locator('tbody tr').count() === 3,'compact list');
  check(await page.getByRole('button',{name:'Подтвердить подписание',exact:true}).count() === 0,'list has no signing controls');
  await page.screenshot({path:resolve(output,'protocol-list.png'),fullPage:true});
  await page.getByLabel('Поиск',{exact:true}).fill('UI-002');
  check(await page.locator('tbody tr').count() === 1,'search');
  await page.getByLabel('Поиск',{exact:true}).fill('');
  await page.getByLabel('Состояние',{exact:true}).selectOption('signed');
  check(await page.locator('tbody tr').count() === 1,'signed filter');
  await page.getByLabel('Состояние',{exact:true}).selectOption('');
  await page.getByRole('link',{name:'Открыть протокол № UI-001'}).click();
  await page.getByRole('heading',{name:'Протокол № UI-001',exact:true}).waitFor();
  check(await page.getByRole('button',{name:'Подтвердить подписание',exact:true}).count() === 0,'draft cannot sign');
  check(await page.getByRole('region',{name:'Этапы протокола'}).getByRole('listitem').count() === 6,'six stages');
  check(await page.locator('table tbody tr').count() === 1,'separate compact participant table');
  await page.screenshot({path:resolve(output,'protocol-detail.png'),fullPage:true});
  await page.getByRole('button',{name:'Заполнить этап «Комиссия»',exact:true}).click();
  await page.getByLabel('Приказ о комиссии — номер').fill('UNSAVED');
  await page.getByRole('button',{name:/Этап 3.*Результаты/}).click();
  check(await page.getByLabel('Приказ о комиссии — номер').inputValue() === 'UNSAVED','switching stage keeps unsaved edits');
  await page.getByRole('button',{name:'Проверить готовность',exact:true}).click();
  await page.getByText('Укажите номер приказа о создании комиссии.',{exact:true}).waitFor();
  await page.getByText('Заполните центральные реквизиты DOCUMENT_ORG_NAME и DOCUMENT_ORG_INN.',{exact:true}).waitFor();
  check(await page.getByRole('link',{name:'Открыть данные Минтруда',exact:true}).count() === 1,'external employer issue has registry destination');
  await page.getByRole('button',{name:'Исправить в редакторе',exact:true}).click();
  check(await page.getByLabel('Приказ о комиссии — номер').inputValue() === 'UNSAVED','readiness correction preserves existing editor input');
  check(await page.getByRole('button',{name:'Зафиксировать фактические результаты комиссии',exact:true}).count() === 0,'server blocking reason prevents recording');
  await page.getByRole('link',{name:'Карточка участника',exact:true}).click();
  await page.getByTestId('mintrud-participant-card').waitFor();
  check(page.url().endsWith('#participant=draft:synthetic-person'),'legacy participant hash');
  await page.getByRole('button',{name:'Вернуться к протоколу',exact:true}).click();
  check(!page.url().includes('#'),'participant back');
  await page.getByRole('link',{name:'← Все протоколы',exact:true}).click();
  await page.getByRole('link',{name:'Открыть протокол № UI-001'}).waitFor();
  check(page.url().endsWith(root),'list back');
  await goto(root+'/older');
  await page.getByRole('heading',{name:'Протокол № UI-OLDER',exact:true}).waitFor();
  check(true,'direct detail outside list limit');
  await goto(root+'/missing');
  await page.getByText('Протокол не найден. Возможно, ссылка устарела.',{exact:true}).waitFor();
  check(await page.getByRole('link',{name:'← Все протоколы',exact:true}).count() === 1,'404 navigation');
  listFails = true;
  await goto(root);
  await page.getByRole('button',{name:'Повторить загрузку',exact:true}).waitFor();
  listFails = false;
  await page.getByRole('button',{name:'Повторить загрузку',exact:true}).click();
  await page.getByRole('link',{name:'Открыть протокол № UI-001'}).waitFor();
  check(true,'list retry');
  write = false;
  await goto(root+'/recorded');
  await page.getByRole('heading',{name:'Протокол № UI-002',exact:true}).waitFor();
  check(await page.getByRole('button',{name:'Подтвердить подписание',exact:true}).count() === 0,'read-only recorded view');
  write = true;
  await goto(root+'/recorded');
  await page.getByRole('button',{name:'Подтвердить подписание',exact:true}).waitFor();
  check(true,'recorded signing entry');
  await goto(root+'/signed');
  await page.getByRole('button',{name:'Скачать скан',exact:true}).waitFor();
  check(await page.locator('input[type=file]').count() === 0,'existing scan cannot be overwritten');
  check(writes.length === 0,'navigation and checks cause no writes');
  await goto(root+'/new');
  await page.getByLabel('Курс',{exact:true}).selectOption('synthetic-course');
  await page.getByText('Новый тестовый участник',{exact:false}).waitFor();
  check(await page.getByText('Ранее сохранённые проекты',{exact:true}).count() === 0,'creation has no huge protocol list');
  await page.getByLabel('Поиск слушателя',{exact:true}).fill('Новый тестовый');
  check(await page.getByRole('checkbox').count() === 1,'candidate search across 68 people');
  await page.getByRole('checkbox').check();
  await page.getByLabel('Поиск слушателя',{exact:true}).fill('Кандидат 66');
  check(await page.getByText(/Выбрано: 1.*Новый тестовый участник/).count() === 1,'selected participant remains visible outside filtered list');
  await page.getByLabel('Поиск слушателя',{exact:true}).fill('Новый тестовый');
  check(await page.getByRole('checkbox').isChecked(),'filter preserves selected participant');
  await page.getByLabel('Номер проекта протокола').fill('UI-NEW');
  await page.getByLabel('Дата протокола (указать вручную)').fill('2026-11-05');
  await page.getByRole('button',{name:'Сохранить проект на 1 участников',exact:true}).click();
  await page.getByRole('heading',{name:'Протокол № UI-NEW',exact:true}).waitFor();
  check(writes.length === 1 && writes[0].path.endsWith('/protocol-drafts'),'create uses only existing draft endpoint');
  check(!('participant_results' in writes[0].body) && writes[0].body.commission_chair === null,'no manufactured commission results');
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:resolve(output,'protocol-mobile.png'),fullPage:true});
  check(errors.length === 0,errors.join('\n'));
  console.log(JSON.stringify({checks,writes:'1 intercepted synthetic creation; no backend calls',errors},null,2));
} finally {
  await context.close(); await browser.close(); await new Promise(resolve => server.httpServer.close(resolve));
}
